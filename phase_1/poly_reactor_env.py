"""
poly_reactor_env.py
===================

FINAL HOFLON reactor environment.

Fixed conventions
-----------------
Transition:
    obs_t -- action_t --> physical ODE --> obs_(t+1)

Action seen by actor:
    [u_I, u_Tc] in [0, 1]^2

Physical actuator conversion:
    f_I = 2.5 * u_I
    T_c = 280 + 120 * u_Tc

Returned observation:
    [A, I, P, R, T, err_P, err_T, int_err_P, int_err_T]

using the settled Idea 3 scaling (Idea 2 transforms frozen as constants).

Reward:
    E_(t+1) = err_P_(t+1)^2 + err_T_(t+1)^2

    reward_t = -E_(t+1)

The reward is therefore attached to the transition generated by action_t.
There is no old previous/current-state reward offset and no change-in-error
term in this final baseline environment.

The mechanistic reactor ODE runs entirely in physical units.
Scaling exists only at the actor/environment boundary.
"""

from __future__ import annotations

import numpy as np
from scipy.integrate import solve_ivp

try:
    import gymnasium as gym
    from gymnasium import spaces
except ImportError:
    import gym
    from gym import spaces


# ===========================================================================
# PHYSICAL REACTOR PARAMETERS
# ===========================================================================

R_GAS = 8.314

RHO = 1000.0
CP = 2000.0
UA = 550.0
V = 1.0

W_A = 100.0
W_S = 80.0
T_FEED = 350.0

MW_A = 0.100
MW_I = 0.165

A_D = 1e9
E_D = 125e3

A_P = 4e4
E_P = 25e3

A_T = 1e6
E_T = 15e3

DELTA_H_RXN = 100e3


# ===========================================================================
# PHYSICAL LIMITS / SETPOINTS
# ===========================================================================

F_I_MIN = 0.0
F_I_MAX = 2.5

TC_MIN = 280.0
TC_MAX = 400.0

P_SETPOINT = 100.0
T_SETPOINT = 350.0

S_CONC = 100.0


# True physical state order:
# [A, I, R, P, T]
DEFAULT_Y0 = np.array(
    [555.555456, 0.0, 0.0, 0.0, 350.0],
    dtype=np.float64,
)


# Physical measurement-noise standard deviation.
# State order:
# [A, I, R, P, T]
DEFAULT_NOISE_STD = np.array(
    [
        2.0,
        0.0,
        0.0,
        0.5,
        0.0005714 * 350.0,
    ],
    dtype=np.float64,
)


# ===========================================================================
# SETTLED IDEA 3 SCALING
# ===========================================================================
#
# Idea 3 keeps the Idea 2 observation scaling, but the fitted quantities are
# frozen here. The environment therefore has NO dataset dependency.
#
# Canonical scaling constants were obtained once from the fixed physical PID
# training-data generation setup:
#     n_runs = 100
#     t_total = 100 h
#     dt = 30 min
#     seed = 123
#
# They must remain unchanged when evaluating models trained on the canonical
# Idea 3 dataset.
# ===========================================================================

SCALE_T_MIN = 345.75434322212493
SCALE_T_MAX = 359.86501951220026
SCALE_T_RANGE = 14.110676290075332
SCALE_T_SETPOINT = 0.30088258639036525
SCALE_MAX_ABS_INT_T = 29274.723414037668


class Idea3Scaler:
    """
    Fixed scaler for the canonical Idea 3 representation.

    Observation:
        [A, I, P, R, T, err_P, err_T, int_err_P, int_err_T]

    Scaling:
        A, I, P, R
            -> physical value / 100

        T
            -> (T - SCALE_T_MIN) / SCALE_T_RANGE

        err_P
            -> 1.0 - P_scaled

        err_T
            -> SCALE_T_SETPOINT - T_scaled

        int_err_P
            -> int_err_P_phys / 100 / 1000

        int_err_T
            -> (int_err_T_phys / SCALE_T_RANGE)
               / SCALE_MAX_ABS_INT_T
    """

    t_min = SCALE_T_MIN
    t_max = SCALE_T_MAX
    t_range = SCALE_T_RANGE
    t_setpoint_scaled = SCALE_T_SETPOINT
    max_abs_int_t_scaled = SCALE_MAX_ABS_INT_T

    def scale_observation(
        self,
        measurement_phys: np.ndarray,
        int_err_p_phys: float,
        int_err_t_phys: float,
    ) -> np.ndarray:

        y = np.asarray(
            measurement_phys,
            dtype=np.float64,
        ).reshape(5)

        A, I, R_rad, P, T = map(
            float,
            y,
        )

        # State scaling.
        A_s = A / S_CONC
        I_s = I / S_CONC
        P_s = P / S_CONC
        R_s = R_rad / S_CONC

        T_s = (
            T - self.t_min
        ) / self.t_range

        # Tracking errors in the same scaled coordinates.
        err_p_s = (
            P_SETPOINT / S_CONC
            - P_s
        )

        err_t_s = (
            self.t_setpoint_scaled
            - T_s
        )

        # Integral-memory features.
        int_p_s = (
            float(int_err_p_phys)
            / S_CONC
            / 1000.0
        )

        int_t_s = (
            float(int_err_t_phys)
            / self.t_range
            / self.max_abs_int_t_scaled
        )

        return np.array(
            [
                A_s,
                I_s,
                P_s,
                R_s,
                T_s,
                err_p_s,
                err_t_s,
                int_p_s,
                int_t_s,
            ],
            dtype=np.float32,
        )


# ===========================================================================
# PHYSICAL REACTOR ODE
# ===========================================================================

def _arrhenius(
    pre_exponential: float,
    activation_energy: float,
    temperature: float,
) -> float:

    return (
        pre_exponential
        * np.exp(
            -activation_energy
            / (
                R_GAS
                * temperature
            )
        )
    )


def reactor_odes(
    t: float,
    y: np.ndarray,
    f_I: float,
    T_c: float,
) -> np.ndarray:
    """
    Physical reactor dynamics.

    State:
        y = [A, I, R, P, T]

    Inputs:
        f_I : initiator feed [kg/h]
        T_c : coolant temperature [K]
    """

    del t

    A, I, R_rad, P, T = map(
        float,
        y,
    )

    F = (
        f_I
        + W_A
        + W_S
    ) / (
        RHO
        * 3600.0
    )

    D = F / V

    k_d = _arrhenius(
        A_D,
        E_D,
        T,
    )

    k_p = _arrhenius(
        A_P,
        E_P,
        T,
    )

    k_t = _arrhenius(
        A_T,
        E_T,
        T,
    )

    r_d = (
        k_d
        * I
        / MW_I
    )

    r_p = (
        k_p
        * R_rad
        * A
        / MW_A
    )

    r_t = (
        k_t
        * R_rad**2
    )

    dA = (
        (W_A / 3600.0) / V
        - D * A
        - r_p * MW_A
    )

    dI = (
        (f_I / 3600.0) / V
        - D * I
        - r_d * MW_I
    )

    dR = (
        2.0 * r_d
        - 2.0 * r_t
    )

    dP = (
        r_p * MW_A
        - D * P
    )

    Q_rxn = (
        DELTA_H_RXN
        * r_p
        * V
    )

    Q_cool = (
        UA
        * (T - T_c)
    )

    Q_flow = (
        RHO
        * CP
        * F
        * (T_FEED - T)
    )

    dT = (
        Q_rxn
        - Q_cool
        + Q_flow
    ) / (
        RHO
        * CP
        * V
    )

    return np.array(
        [
            dA,
            dI,
            dR,
            dP,
            dT,
        ],
        dtype=np.float64,
    )


# ===========================================================================
# FINAL GYM ENVIRONMENT
# ===========================================================================

class PolymerisationEnv(gym.Env):
    """
    Final HOFLON environment.

    Interface
    ---------
    action:
        [u_I, u_Tc] in [0,1]^2

    observation:
        [A, I, P, R, T,
         err_P, err_T,
         int_err_P, int_err_T]

    transition:
        obs_t
          -> action_t
          -> physical ODE integration
          -> measurement of s_(t+1)
          -> scaled obs_(t+1)

    reward:
        -(err_P_(t+1)^2 + err_T_(t+1)^2)

    Reward therefore belongs to the action that generated the next state.
    """

    metadata = {
        "render_modes": [],
    }

    def __init__(
        self,
        *,
        dt: float = 30.0 * 60.0,
        t_total: float = 100.0 * 3600.0,
        seed: int | None = None,
        y0: np.ndarray | None = None,
        noise_std: np.ndarray | None = None,
        saturation_tol: float = 1e-3,
    ):
        super().__init__()

        if dt <= 0.0:
            raise ValueError(
                "dt must be positive."
            )

        if t_total <= 0.0:
            raise ValueError(
                "t_total must be positive."
            )

        self.dt = float(dt)
        self.t_total = float(
            t_total
        )

        self.n_steps = int(
            self.t_total
            // self.dt
        )

        if self.n_steps < 1:
            raise ValueError(
                "t_total must contain at least one full step."
            )

        self.y0 = np.asarray(
            DEFAULT_Y0
            if y0 is None
            else y0,
            dtype=np.float64,
        ).reshape(5)

        self.noise_std = np.asarray(
            DEFAULT_NOISE_STD
            if noise_std is None
            else noise_std,
            dtype=np.float64,
        ).reshape(5)

        if np.any(
            self.noise_std < 0.0
        ):
            raise ValueError(
                "noise_std values must be non-negative."
            )

        self.saturation_tol = float(
            saturation_tol
        )

        # ---------------------------------------------------------------
        # Settled Idea 3 scaler.
        # All scaling constants are frozen in this module.
        # No dataset is loaded or referenced at runtime.
        # ---------------------------------------------------------------

        self.scaler = Idea3Scaler()

        # ---------------------------------------------------------------
        # Spaces seen by actor
        # ---------------------------------------------------------------

        self.action_space = spaces.Box(
            low=np.zeros(
                2,
                dtype=np.float32,
            ),
            high=np.ones(
                2,
                dtype=np.float32,
            ),
            dtype=np.float32,
        )

        # Do not clip observations to training-data range.
        # Going outside it is meaningful OOD behaviour.
        self.observation_space = spaces.Box(
            low=-np.inf,
            high=np.inf,
            shape=(9,),
            dtype=np.float32,
        )

        self._initial_seed = seed

        # Runtime state.
        self._rng: np.random.Generator | None = None

        self.y_true = (
            self.y0.copy()
        )

        self.y_meas = (
            self.y0.copy()
        )

        self.int_err_p_phys = 0.0
        self.int_err_t_phys = 0.0

        self.step_count = 0
        self.time_s = 0.0


    # =======================================================================
    # HELPERS
    # =======================================================================

    def _measure(
        self,
        y_true: np.ndarray,
    ) -> np.ndarray:

        return (
            y_true
            + self._rng.normal(
                loc=0.0,
                scale=self.noise_std,
                size=5,
            )
        )


    @staticmethod
    def _scaled_to_physical_action(
        action: np.ndarray,
    ) -> tuple[float, float]:

        u_I = float(
            action[0]
        )

        u_Tc = float(
            action[1]
        )

        f_I = (
            F_I_MIN
            + u_I
            * (
                F_I_MAX
                - F_I_MIN
            )
        )

        T_c = (
            TC_MIN
            + u_Tc
            * (
                TC_MAX
                - TC_MIN
            )
        )

        return (
            float(f_I),
            float(T_c),
        )


    def _physical_errors(
        self,
        measurement_phys: np.ndarray,
    ) -> tuple[float, float]:

        P = float(
            measurement_phys[3]
        )

        T = float(
            measurement_phys[4]
        )

        return (
            float(
                P_SETPOINT
                - P
            ),
            float(
                T_SETPOINT
                - T
            ),
        )


    def _make_observation(
        self,
        measurement_phys: np.ndarray,
    ) -> np.ndarray:

        return (
            self.scaler.scale_observation(
                measurement_phys=measurement_phys,
                int_err_p_phys=self.int_err_p_phys,
                int_err_t_phys=self.int_err_t_phys,
            )
        )


    @staticmethod
    def _reward_from_next_obs(
        next_obs: np.ndarray,
    ) -> float:
        """
        FINAL REWARD CONVENTION.

        Observation indices:
            5 -> scaled polymer error
            6 -> scaled temperature error

        reward_t =
            -(err_P_(t+1)^2 + err_T_(t+1)^2)

        This is intentionally the NEXT state, not the current state.
        """

        err_p_next = float(
            next_obs[5]
        )

        err_t_next = float(
            next_obs[6]
        )

        next_tracking_error = (
            err_p_next**2
            + err_t_next**2
        )

        return float(
            -next_tracking_error
        )


    def _build_info(
        self,
        *,
        obs: np.ndarray,
        reward: float | None = None,
        action_scaled: np.ndarray | None = None,
        action_physical: tuple[float, float] | None = None,
    ) -> dict:

        err_p_phys, err_t_phys = (
            self._physical_errors(
                self.y_meas
            )
        )

        info = {
            "time_s": float(
                self.time_s
            ),
            "time_min": float(
                self.time_s / 60.0
            ),

            # Hidden true physical plant.
            "A_true": float(
                self.y_true[0]
            ),
            "I_true": float(
                self.y_true[1]
            ),
            "R_true": float(
                self.y_true[2]
            ),
            "P_true": float(
                self.y_true[3]
            ),
            "T_true": float(
                self.y_true[4]
            ),

            # Physical noisy measurement used by actor.
            "A": float(
                self.y_meas[0]
            ),
            "I": float(
                self.y_meas[1]
            ),
            "R": float(
                self.y_meas[2]
            ),
            "P": float(
                self.y_meas[3]
            ),
            "T": float(
                self.y_meas[4]
            ),

            # Physical tracking errors.
            "err_P_phys": float(
                err_p_phys
            ),
            "err_T_phys": float(
                err_t_phys
            ),

            # Scaled tracking errors used in reward.
            "err_P_scaled": float(
                obs[5]
            ),
            "err_T_scaled": float(
                obs[6]
            ),

            "tracking_error_scaled": float(
                obs[5] ** 2
                + obs[6] ** 2
            ),

            "int_err_P_phys": float(
                self.int_err_p_phys
            ),
            "int_err_T_phys": float(
                self.int_err_t_phys
            ),
        }

        if reward is not None:
            info["reward"] = float(
                reward
            )

        if action_scaled is not None:
            info["u_I"] = float(
                action_scaled[0]
            )
            info["u_Tc"] = float(
                action_scaled[1]
            )

        if action_physical is not None:
            info["f_I"] = float(
                action_physical[0]
            )
            info["T_c"] = float(
                action_physical[1]
            )

        return info


    # =======================================================================
    # GYM API
    # =======================================================================

    def reset(
        self,
        *,
        seed: int | None = None,
        options: dict | None = None,
    ):

        try:
            super().reset(
                seed=seed
            )
        except TypeError:
            super().reset()

        del options

        effective_seed = (
            self._initial_seed
            if seed is None
            else seed
        )

        self._rng = (
            np.random.default_rng(
                effective_seed
            )
        )

        # Reset physical plant.
        self.y_true = (
            self.y0.copy()
        )

        # Reset controller-history features.
        self.int_err_p_phys = 0.0
        self.int_err_t_phys = 0.0

        self.step_count = 0
        self.time_s = 0.0

        # Measure s_0 ONCE.
        self.y_meas = self._measure(
            self.y_true
        )

        obs = self._make_observation(
            self.y_meas
        )

        info = self._build_info(
            obs=obs
        )

        return (
            obs,
            info,
        )


    def step(
        self,
        action,
    ):

        action = np.asarray(
            action,
            dtype=np.float64,
        ).reshape(2)

        if not np.all(
            np.isfinite(action)
        ):
            raise ValueError(
                f"Action contains non-finite values: {action}"
            )

        # Environment safety bound.
        action = np.clip(
            action,
            0.0,
            1.0,
        )

        # ---------------------------------------------------------------
        # 1. Current state s_t / observation_t
        # ---------------------------------------------------------------

        current_measurement = (
            self.y_meas.copy()
        )

        err_p_current_phys, err_t_current_phys = (
            self._physical_errors(
                current_measurement
            )
        )

        # ---------------------------------------------------------------
        # 2. Update integral-memory state associated with transition
        # ---------------------------------------------------------------
        #
        # This follows the processed PID dataset convention as closely as
        # possible for a non-PI actor:
        #
        # integrate while the selected action is not at an actuator bound;
        # freeze at saturation.
        # ---------------------------------------------------------------

        u_I = float(
            action[0]
        )

        u_Tc = float(
            action[1]
        )

        if (
            u_I > self.saturation_tol
            and u_I < 1.0 - self.saturation_tol
        ):
            int_p_next = (
                self.int_err_p_phys
                + err_p_current_phys
                * self.dt
            )
        else:
            int_p_next = (
                self.int_err_p_phys
            )

        if (
            u_Tc > self.saturation_tol
            and u_Tc < 1.0 - self.saturation_tol
        ):
            int_t_next = (
                self.int_err_t_phys
                + err_t_current_phys
                * self.dt
            )
        else:
            int_t_next = (
                self.int_err_t_phys
            )

        # ---------------------------------------------------------------
        # 3. Convert scaled action -> physical actuator values
        # ---------------------------------------------------------------

        f_I, T_c = (
            self._scaled_to_physical_action(
                action
            )
        )

        # ---------------------------------------------------------------
        # 4. Apply action_t to TRUE physical state and integrate to s_(t+1)
        # ---------------------------------------------------------------

        sol = solve_ivp(
            lambda t, y: reactor_odes(
                t,
                y,
                f_I,
                T_c,
            ),
            (
                0.0,
                self.dt,
            ),
            self.y_true,
            method="BDF",
            atol=1e-8,
            rtol=1e-6,
        )

        if not sol.success:
            raise RuntimeError(
                "Reactor integration failed: "
                f"{sol.message}"
            )

        self.y_true = (
            sol.y[:, -1]
            .astype(
                np.float64
            )
        )

        # Integral memory advances with the transition.
        self.int_err_p_phys = float(
            int_p_next
        )

        self.int_err_t_phys = float(
            int_t_next
        )

        self.step_count += 1

        self.time_s = (
            self.step_count
            * self.dt
        )

        # ---------------------------------------------------------------
        # 5. Measure genuine next state s_(t+1)
        # ---------------------------------------------------------------

        self.y_meas = self._measure(
            self.y_true
        )

        # ---------------------------------------------------------------
        # 6. Build genuine next observation
        # ---------------------------------------------------------------

        obs_next = self._make_observation(
            self.y_meas
        )

        # ---------------------------------------------------------------
        # 7. FINAL reward:
        #
        #       reward_t = -E_(t+1)
        #
        # where E_(t+1) uses the scaled next-state errors contained in
        # obs_next.
        # ---------------------------------------------------------------

        reward = (
            self._reward_from_next_obs(
                obs_next
            )
        )

        terminated = False

        truncated = (
            self.step_count
            >= self.n_steps
        )

        info = self._build_info(
            obs=obs_next,
            reward=reward,
            action_scaled=action,
            action_physical=(
                f_I,
                T_c,
            ),
        )

        return (
            obs_next,
            reward,
            terminated,
            truncated,
            info,
        )


# ===========================================================================
# CONVENIENCE FACTORY
# ===========================================================================

def make_env(
    *,
    dt: float = 30.0 * 60.0,
    t_total: float = 100.0 * 3600.0,
    seed: int | None = 123,
    noise_std: np.ndarray | None = None,
) -> PolymerisationEnv:
    """Create the settled Idea 3 polymerisation environment."""

    return PolymerisationEnv(
        dt=dt,
        t_total=t_total,
        seed=seed,
        noise_std=noise_std,
    )
